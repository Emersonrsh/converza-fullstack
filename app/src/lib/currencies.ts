let names: Intl.DisplayNames | null | undefined;
/** "Dirham dos Emirados Árabes Unidos" para AED. */
export function currencyName(code: string): string {
  if (names === undefined) {
    try { names = new Intl.DisplayNames(['pt-BR'], { type: 'currency' }); } catch { names = null; }
  }
  try {
    const n = names?.of(code);
    if (n && n !== code) return n.charAt(0).toUpperCase() + n.slice(1);
  } catch { /* código desconhecido */ }
  return code;
}

const fold = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
/** Busca por código ou nome, sem diferenciar acento e maiúscula ("dolar" acha USD, CAD, AUD...). */
export function matchCurrency(code: string, q: string): boolean {
  const t = fold(q.trim());
  return !t || fold(code).includes(t) || fold(currencyName(code)).includes(t);
}
